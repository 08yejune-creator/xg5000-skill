# 시작/정지 자기유지 모터와 5초 지연 램프 예제.
#
# 표기: + 는 병렬(OR), * 는 직렬(AND), ! 는 NC 접점. 괄호로 묶을 수 있다.
# 렁은 ("coil", 코일이름, 식) 또는 ("ton", 타이머이름, 직렬 입력식, 설정시간 ms)이다.
# 타이머 출력 접점은 타이머이름.Q, 시스템 플래그는 _T1S처럼 이름 그대로 쓴다.
# 주소가 없는 이름은 주소 없는 BOOL 변수가 된다.
# 주소는 템플릿 프로젝트의 모듈 구성에 맞춰 적는다. 아래는 슬롯 0이 입력, 슬롯 2가 출력인 경우다.

INPUT_ADDRESSES = {
    "시작버튼": "%IX0.0.0",
    "정지버튼": "%IX0.0.1",
}

OUTPUT_ADDRESSES = {
    "모터": "%QX0.2.0",
    "가동램프": "%QX0.2.1",
}

# (구역 제목, 렁 목록)
PROGRAM = [
    ("모터 자기유지", [
        ("coil", "모터", "(시작버튼+모터)*!정지버튼"),
    ]),
    ("모터가 5초 돌면 램프 점등", [
        ("ton", "가동지연", "모터", 5000),
        ("coil", "가동램프", "가동지연.Q"),
    ]),
]
